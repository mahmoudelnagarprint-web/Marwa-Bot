def detect(text: str) -> Optional[Dict[str, Any]]:
    """أول نداء قاطع في الرسالة، أو None.
    «يا <اسم>» لأي شخصية (في أي موضع) قاطع دائمًا؛ أسماء الدلع السافرة قاطعة كذلك.
    يعيد: {'agent_id', 'name', 'persona', 'mode', 'index'} أو None."""
    norm = normalize(text)
    if not norm.strip():
        return None
    hits: List[Tuple[int, str, str, Dict[str, Any], str]] = []
    for agent_id, p in _PERSONAS.items():
        for raw, gated in p["names"]:
            n = normalize(raw)
            if not n:
                continue
            # 1) نداء «يا <اسم>» — «يا» في بداية كلمة (بداية الرسالة أو بعد مسافة)
            m = re.search(rf"(?:^|\s)يا\s*{re.escape(n)}", norm)
            if m:
                hits.append((m.start(), agent_id, raw, p, "voc"))
                continue
            # 2) اسم دلع سافر (غير الشائع) — يعمل بدون «يا»
            if not gated:
                idx = norm.find(n)
                if idx >= 0:
                    hits.append((idx, agent_id, raw, p, "bare"))
    if not hits:
        return None
    hits.sort(key=lambda h: h[0])
    idx, agent_id, raw, p, mode = hits[0]
    return {
        "agent_id": agent_id,
        "name": raw,
        "persona": p["display"],
        "mode": mode,
        "index": idx,
    }


def is_bare_call(text: str, hit: Dict[str, Any]) -> bool:
    """هل الرسالة مجرد نداء بالاسم بلا طلب مصاحب؟
    (بعد حذف كل أسماء الشخصيات و«يا» ما تبقاش أي حروف أو أرقام)"""
    rem = normalize(text)
    for p in _PERSONAS.values():
        for raw, _gated in p["names"]:
            rem = rem.replace(normalize(raw), " ")
    rem = rem.replace("يا", " ")
    return not re.search(r"[\w\u0600-\u06FF]", rem)


def persona_card(agent_id: str) -> Optional[str]:
    """بطاقة هوية الشخصية عند النداء المجرد — None لو الوكيل عنده بطاقته الخاصة."""
    p = _PERSONAS.get(agent_id)
    if not p:
        return None
    return p.get("card") or None


def signature(agent_id: str) -> str:
    """سطر التوقيع باسم الشخصية — «كوكو (التسويق والعروض):» — فارغ لو مجهول."""
    p = _PERSONAS.get(agent_id)
    if not p:
        return ""
    return f'{p["display"]} ({p["role"]}):'


