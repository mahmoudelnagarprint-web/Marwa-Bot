_DIACRITICS = "\u064B\u064C\u064D\u064E\u064F\u0650\u0651\u0652\u0640"  # تشكيل + تطويل


def normalize(text: str) -> str:
    """تطبيع خفيف للمطابقة: بلا تشكيل/تطويل، أ/إ/آ→ا، ى→ي، ة→ه."""
    t = (text or "")
    for ch in _DIACRITICS:
        t = t.replace(ch, "")
    t = t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    t = t.replace("ى", "ي").replace("ة", "ه")
    return t.lower()


